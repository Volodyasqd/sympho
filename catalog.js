// Функція додавання в кошик
function addToCart(id) {
    let cart = JSON.parse(localStorage.getItem('sympho_cart')) || [];
    const product = products.find(p => p.id === id);
    
    if (!product) {
        console.error("Товар не знайдено з ID:", id);
        return;
    }

    const existing = cart.find(item => item.id === id);
    if (existing) {
        existing.count += 1;
    } else {
        cart.push({
            id: product.id,
            name: product.name,
            article: product.article,
            price: product.price,
            count: 1
        });
    }

    localStorage.setItem('sympho_cart', JSON.stringify(cart));
    console.log("Кошик оновлено:", cart);
    updateCartCounter();
    alert("Додано в кошик: " + product.name);
}

// Оновлення цифри на іконці
function updateCartCounter() {
    const cart = JSON.parse(localStorage.getItem('sympho_cart')) || [];
    const total = cart.reduce((sum, item) => sum + item.count, 0);
    const badge = document.getElementById('cart-count');
    if (badge) {
        badge.innerText = total;
        badge.style.display = total > 0 ? 'block' : 'none';
    }
}

// Викликаємо при старті
window.addEventListener('DOMContentLoaded', updateCartCounter);
function liveSearch() {
    const input = document.getElementById('searchInput');
    const resultsBlock = document.getElementById('live-results');
    const query = input.value.trim().toLowerCase();

    // Якщо в полі менше 2 символів — ховаємо підказки
    if (query.length < 2) {
        resultsBlock.style.display = 'none';
        return;
    }

    // Шукаємо збіги (по назві, артикулу або опису)
    const matches = products.filter(p => 
        p.name.toLowerCase().includes(query) || 
        p.article.toLowerCase().includes(query) ||
        (p.desc && p.desc.toLowerCase().includes(query))
    ).slice(0, 5); // Показуємо тільки перші 5 збігів, щоб не захаращувати екран

    if (matches.length > 0) {
        resultsBlock.style.display = 'block';
        resultsBlock.innerHTML = matches.map(p => `
            <div onclick="window.location.href='product.html?id=${p.id}'" style="
                padding: 10px; 
                border-bottom: 1px solid #eee; 
                cursor: pointer; 
                display: flex; 
                align-items: center; 
                gap: 10px;">
                <img src="${p.images[0]}" style="width: 30px; height: 30px; object-fit: contain;">
                <div>
                    <div style="font-size: 14px; font-weight: bold;">${p.name}</div>
                    <div style="font-size: 12px; color: #888;">Арт: ${p.article}</div>
                </div>
            </div>
        `).join('');
    } else {
        resultsBlock.style.display = 'none';
    }
}

